#!/usr/bin/env bash
# vim: set ft=sh:
#
# Regenerates config/hypr/hyprsunset.conf from the shared schedule in
# bin/lib/temperature-profile.sh (issue 0013).
#
# hyprsunset is a daemon that reads its conf once at startup, not a script,
# so there is no live "read the same table" option without restarting the
# user's working night-light -- this generator instead makes the checked-in
# conf file derived output. Run it by hand after editing
# TEMPERATURE_PROFILE; it does not restart hyprsunset, so a running session
# picks up the new schedule on its next natural restart.
#
# Not wired into install.sh: it edits a tracked file in this repo, it isn't
# an install-time system step.

set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$here/../.." && pwd)"

# shellcheck source=./temperature-profile.sh
source "$here/temperature-profile.sh"

out="$repo_root/config/hypr/hyprsunset.conf"

{
  echo "# GENERATED by bin/lib/generate-hyprsunset-conf.sh from"
  echo "# bin/lib/temperature-profile.sh -- do not hand-edit the schedule"
  echo "# here; edit TEMPERATURE_PROFILE and re-run the generator."
  echo

  first=1
  for entry in "${TEMPERATURE_PROFILE[@]}"; do
    IFS=: read -r ehour ekelvin egamma elabel <<< "$entry"
    [[ "$first" -eq 1 ]] || echo
    first=0
    echo "# $elabel"
    echo "profile {"
    echo "    time = ${ehour}:00"
    echo "    temperature = ${ekelvin}"
    if [[ "$egamma" != "1.0" ]]; then
      echo "    gamma = ${egamma}"
    fi
    echo "}"
  done
} > "$out"

echo "wrote $out"
